  var language = /^ru(?:-|$)/i.test(navigator.language || '') ? 'ru' : 'zh';

  function t(key) {
    var dictionary = language === 'ru' ? ru : zh;
    return Object.prototype.hasOwnProperty.call(dictionary, key) ? dictionary[key] : (zh[key] || '');
  }

  function localize(root) {
    document.documentElement.lang = language === 'ru' ? 'ru' : 'zh-CN';
    Array.prototype.forEach.call(root.querySelectorAll('[data-i18n]'), function (node) {
      node.textContent = t(node.getAttribute('data-i18n'));
    });
    ['aria-label', 'title', 'placeholder', 'suggest'].forEach(function (attribute) {
      var marker = 'data-i18n-' + attribute;
      Array.prototype.forEach.call(root.querySelectorAll('[' + marker + ']'), function (node) {
        node.setAttribute(attribute === 'suggest' ? 'data-suggest' : attribute, t(node.getAttribute(marker)));
      });
    });
  }

  function relativeTime(timestamp) {
    if (!timestamp) return '';
    var elapsed = Math.max(0, Date.now() - timestamp);
    if (elapsed < 60000) return t('justNow');
    if (language === 'ru') {
      var format = new Intl.RelativeTimeFormat('ru', { numeric: 'always' });
      if (elapsed < 3600000) return format.format(-Math.floor(elapsed / 60000), 'minute');
      if (elapsed < 86400000) return format.format(-Math.floor(elapsed / 3600000), 'hour');
      if (elapsed < 604800000) return format.format(-Math.floor(elapsed / 86400000), 'day');
      return new Date(timestamp).toLocaleDateString('ru');
    }
    if (elapsed < 3600000) return Math.floor(elapsed / 60000) + ' 分钟前';
    if (elapsed < 86400000) return Math.floor(elapsed / 3600000) + ' 小时前';
    if (elapsed < 604800000) return Math.floor(elapsed / 86400000) + ' 天前';
    var date = new Date(timestamp);
    return (date.getMonth() + 1) + '月' + date.getDate() + '日';
  }

  window.DSHI18n = { t: t, localize: localize, relativeTime: relativeTime };
